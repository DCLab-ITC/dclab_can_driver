#!/usr/bin/env python3
"""Writes frame_vectors.inc: inputs and the Python driver's bytes for them
(can_driver/dclab_frames.py and the Robomaster/Vesc modules' arithmetic),
so test_frames.cpp checks that the C++ build sends and reads the same."""
import os
import random
import struct
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "..", "can_driver"))
from can_driver import dclab_frames as frames  # noqa: E402

rng = random.Random(20261018)


def f32(x):
    return struct.unpack("<f", struct.pack("<f", x))[0]


def cfloat(x):
    if x != x:
        return "NAN"
    if x in (float("inf"), float("-inf")):
        return ("-" if x < 0 else "") + "INFINITY"
    return repr(float(x))


def cf(x):
    """a float literal"""
    text = cfloat(x)
    return text if text.endswith(("NAN", "INFINITY")) else text + "f"


def cbytes(b):
    return "{" + ", ".join(str(v) for v in b) + "}"


out = []
goals = [0.0, 1.0, -1.0, 3.14159, 1e-30, -12345.678, 1e30, float("inf"), float("nan")]
rows = []
for _ in range(300):
    m1e, m2e = rng.random() < 0.7, rng.random() < 0.5
    mode1, mode2 = rng.choice(range(7)), rng.choice(range(7))
    g1 = f32(rng.choice(goals) if rng.random() < 0.3 else rng.uniform(-1000, 1000))
    g2 = f32(rng.choice(goals) if rng.random() < 0.3 else rng.uniform(-1000, 1000))
    try:
        data = frames.motor_command(m1e, mode1, g1, m2e, mode2, g2)
        ok = 1
    except ValueError:
        data, ok = b"", 0
    rows.append("{%d, %d, %s, %d, %d, %s, %d, %d, %s}" % (
        m1e, mode1, cf(g1), m2e, mode2, cf(g2), ok, len(data), cbytes(data.ljust(8, b"\0"))))
out.append("const MotorVector motor_vectors[] = {\n  " + ",\n  ".join(rows) + "};")

rows = []
for _ in range(300):
    vals = [f32(rng.choice([rng.uniform(-0.2, 1.2), 0.5, 1.0, 0.0, float("nan"), rng.randrange(16384) / 16383.0,
                            (rng.randrange(16383) + 0.5) / 16383.0])) for _ in range(4)]
    kind = rng.choice((2, 3))
    data = frames.controller_pwm(vals) if kind == 2 else frames.controller_servo(vals)
    rows.append("{%d, {%s}, %s}" % (kind, ", ".join(cf(v) for v in vals), cbytes(data)))
out.append("const ControllerVector controller_vectors[] = {\n  " + ",\n  ".join(rows) + "};")

rows = []
for _ in range(50):
    d = [rng.random() < 0.5 for _ in range(4)]
    s = [rng.random() < 0.5 for _ in range(6)]
    rows.append("{{%s}, {%s}, %s}" % (", ".join(str(int(x)) for x in d), ", ".join(str(int(x)) for x in s),
                                      cbytes(frames.controller_digital(d, s))))
out.append("const DigitalVector digital_vectors[] = {\n  " + ",\n  ".join(rows) + "};")

LIMITS = {0: (10.0, 1000.0), 1: (20.0, 819.2)}
rows = []
for _ in range(200):
    cur = [f32(rng.uniform(-25, 25)) for _ in range(4)]
    types = [rng.choice((0, 1, 2)) for _ in range(4)]
    data = bytearray(8)
    for i in range(4):  # Robomaster.current
        max_current, scale = LIMITS.get(types[i], LIMITS[0])
        value = max(-max_current, min(max_current, float(cur[i])))
        struct.pack_into(">h", data, 2 * i, int(value * scale))
    rows.append("{{%s}, {%s}, %s}" % (", ".join(cf(v) for v in cur), ", ".join(map(str, types)), cbytes(data)))
out.append("const RobomasterVector robomaster_vectors[] = {\n  " + ",\n  ".join(rows) + "};")

rows = []
for _ in range(200):
    packet = rng.randrange(5)
    goal = f32([rng.uniform(-2, 2), rng.uniform(-100, 100), rng.uniform(-100, 100), rng.uniform(-50000, 50000),
                rng.uniform(-360, 360)][packet])
    value = [max(-1.0, min(1.0, goal)) * 1e5, goal * 1e3, goal * 1e3, goal, goal * 1e6][packet]  # Vesc.command
    rows.append("{%d, %s, %s}" % (packet, cf(goal), cbytes(struct.pack(">i", int(value)))))
out.append("const VescVector vesc_vectors[] = {\n  " + ",\n  ".join(rows) + "};")

rows = []
for _ in range(200):
    d = bytes(rng.randrange(256) for _ in range(8))
    analog, digital = frames.sensor_inputs(d)
    q = frames.imu_quaternion(d)
    pos = frames.encoder_positions(d)
    rows.append("{%s, {%s}, {%s}, {%s}, {%s}}" % (
        cbytes(d), ", ".join(cf(f32(a)) for a in analog), ", ".join(str(int(x)) for x in digital),
        ", ".join(cfloat(v) for v in q), ", ".join(cf(v) for v in pos)))
out.append("const DecodeVector decode_vectors[] = {\n  " + ",\n  ".join(rows) + "};")

est = frames.SpeedEstimator(0.3)
rows = []
t = 100.0
for _ in range(100):
    can_id, slot = rng.choice((101, 102, 250)), rng.randrange(2)
    pos = f32(rng.uniform(-10, 10))
    t += rng.choice((0.0, 0.001, 0.002, 0.0137))
    rows.append("{%d, %d, %s, %s, %s}" % (can_id, slot, cf(pos), cfloat(t), cfloat(f32(est.update((can_id, slot), pos, t)))))
out.append("const SpeedVector speed_vectors[] = {\n  " + ",\n  ".join(rows) + "};")

with open(os.path.join(os.path.dirname(__file__), "frame_vectors.inc"), "w") as f:
    f.write("// Generated by make_vectors.py from the Python driver; do not edit.\n" + "\n".join(out) + "\n")
